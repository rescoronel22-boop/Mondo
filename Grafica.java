	// Metodo per stamparli fianco a fianco nel cmd
    public static void stampaBattagliaAffiancata(int variante) {
        String[] righeEroe = getEroe().split("\n");
        String[] righeMostro = getMostroColorato(variante).split("\n");

        int maxRighe = Math.max(righeEroe.length, righeMostro.length);

        for (int i = 0; i < maxRighe; i++) {
            String rigaE = (i < righeEroe.length) ? righeEroe[i] : "";
            String rigaM = (i < righeMostro.length) ? righeMostro[i] : "";

            // Stampa l'eroe a sinistra e il mostro a destra con uno spazio fisso in mezzo
            System.out.printf("%-40s   vs   %s%n", rigaE, rigaM);
        }
    }
	
